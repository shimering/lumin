const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const root=path.resolve(__dirname,'..'),uuid=n=>'00000000-0000-4000-8000-'+String(n).padStart(12,'0');
const migration=name=>fs.readFileSync(path.join(root,'supabase/migrations',name),'utf8');

test('orthodontic visit invoices use their own fees and effective doctors in dashboard payroll',async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec(fs.readFileSync(path.join(__dirname,'fixtures/clinic-management.sql'),'utf8'));
  await db.exec(`
    delete from private.hr_doctor_salary_transfers; delete from public.patient_invoice_items;
    delete from public.patient_invoices; delete from public.patients;
    alter table public.patient_invoices alter column id add generated by default as identity,
      add column invoice_date date,add column created_by uuid,add column updated_at timestamptz,
      add unique(patient_id,invoice_date),alter column status set default 'unpaid';
    alter table public.patient_invoice_items alter column id add generated by default as identity,
      add column doctor_name text,add column operation_name text,add column tooth_id text,add column surfaces text[],add unique(finding_id);
    alter table public.dental_operations add column price numeric default 0;
    alter table private.hr_doctor_salary_transfers add primary key(finding_id),add column transferred_by uuid,add column transferred_at timestamptz default now();
    create function private.is_active_user() returns boolean language sql as $$select true$$;
  `);
  const assignments=migration('20260924091500_split_doctor_salary_by_procedure_steps.sql');
  await db.exec(assignments.slice(assignments.indexOf('create or replace function private.doctor_salary_assignment_signature('),assignments.indexOf('-- Existing transfers')));
  await db.exec(migration('20261013143556_clinic_management_overview.sql'));
  await db.exec(migration('20261013212226_automatic_procedure_payroll_on_invoice.sql'));
  await db.exec(migration('20260919163000_add_ortho_package_procedures.sql'));
  await db.exec('drop function private.chart_finding_by_id(jsonb,uuid)');
  await db.exec(migration('20261020133050_ortho_visit_billing_and_payroll.sql'));
  await db.exec(migration('20261027212346_optimize_hr_finding_lookup.sql'));
  await db.exec(migration('20261027213009_batch_clinic_payroll_finding_reads.sql'));
  await db.exec(migration('20261027213238_skip_absent_payroll_chart_findings.sql'));
  await db.exec(fs.readFileSync(path.join(__dirname,'fixtures/ortho-visit-doctor-sync.sql'),'utf8'));
  await db.query(`insert into public.dental_operations(id,code,name,price,is_ortho_package) values($1,'ortho','Orthodontics',5000,true)`,[uuid(50)]);
  const visit=(id,price,extra={})=>({id:uuid(id),visitNumber:id-60,price,status:'C',date:'2026-10-13T10:00:00Z',createdAt:'2026-10-12T10:00:00Z',...extra});
  const parent={id:uuid(60),code:'ortho',price:5000,status:'In',doctorId:uuid(1),doctorName:'Dr A',isOrthoPackage:true,
    orthoVisits:[visit(61,200,{doctorId:uuid(2)}),visit(62,350),visit(63,100,{status:'P'})]};
  let chart={_meta:{mouthOperations:[parent]}};
  await db.query('insert into public.patients values($1,$2,$3)',[uuid(10),'Patient A',JSON.stringify(chart)]);
  const invoice=async ids=>(await db.query(`select * from public.add_chart_findings_to_patient_invoice($1,$2::uuid[],'2026-10-13')`,[uuid(10),ids.map(uuid)])).rows[0];
  const save=()=>db.query('update public.patients set chart_state=$1 where id=$2',[JSON.stringify(chart),uuid(10)]);
  const call=async sql=>(await db.query('select '+sql+' result')).rows[0].result;
  const item=async id=>(await db.query('select * from public.patient_invoice_items where finding_id=$1',[uuid(id)])).rows[0];
  const transfer=async id=>(await db.query('select * from private.hr_doctor_salary_transfers where finding_id=$1',[uuid(id)])).rows[0];

  await t.test('each visit is a separate invoice item; packages and zero fees cannot be charged',async()=>{
    await assert.rejects(invoice([60]),/cannot be invoiced directly/);
    const result=await invoice([61,62,63]);assert.equal(Number(result.total_amount),650);assert.equal(result.added_count,3);
    assert.equal(Number((await item(61)).unit_price),200);assert.equal((await item(61)).doctor_id,uuid(1),'Main doctor overrides stale child assignment');
    assert.equal((await item(61)).doctor_name,'Dr A');assert.match((await item(61)).operation_name,/Visit 1/);
    assert.equal((await transfer(61)).doctor_id,uuid(1));assert.equal(await transfer(63),undefined,'Planned visit waits for completion');
    assert.equal((await invoice([61])).added_count,0,'Repeated invoicing cannot duplicate the visit');
    const day=await call(`public.get_clinic_doctor_day_payroll('2026-10-13','${uuid(1)}')`);
    assert.equal(day.ready_amount,165);assert.equal(day.untransferred_amount,0);
    const overview=await call("public.get_clinic_management_overview('2026-10-13','2026-10-13')");
    assert.equal(overview.hr.payroll_amount,165);assert.equal(overview.hr.payroll_invoice_count,1);
    parent.orthoVisits.push(visit(64,0));await save();await assert.rejects(invoice([64]),/greater than zero/);
  });
  await t.test('tooth packages, status changes and individual doctors use the same salary pipeline',async()=>{
    parent.doctorId=null;parent.doctorName='';parent.orthoVisits[0].doctorId=uuid(2);
    parent.orthoVisits[1].doctorId=uuid(1);parent.orthoVisits[2].doctorId=uuid(2);parent.orthoVisits[2].status='C';
    chart={36:{wholeOperations:[parent]}};await save();
    assert.equal((await item(61)).doctor_id,uuid(2));assert.equal((await transfer(61)).doctor_id,uuid(2));
    assert.equal((await item(63)).operation_status,'C');assert.equal((await transfer(63)).doctor_id,uuid(2));
    const fixed=await call(`public.get_clinic_doctor_day_payroll('2026-10-13','${uuid(2)}')`);assert.equal(fixed.ready_amount,200,'Fixed compensation is per visit');
    const percentage=await call(`public.get_clinic_doctor_day_payroll('2026-10-13','${uuid(1)}')`);assert.equal(percentage.ready_amount,105);
    parent.orthoVisits[1].date='2026-10-14T12:00:00Z';await save();
    assert.equal((await call(`public.get_clinic_doctor_day_payroll('2026-10-14','${uuid(1)}')`)).ready_amount,105,'Payroll follows the clinical visit date');
    parent.orthoVisits[1].price=999;await save();assert.equal(Number((await item(62)).unit_price),350,'Invoiced price remains a snapshot');
  });
  await t.test('late main-doctor assignment syncs invoices without paying salaries or exposing trigger helpers',async()=>{
    parent.doctorId=uuid(1);parent.doctorName='Dr A';await save();
    assert.equal((await item(61)).doctor_id,uuid(1));assert.equal((await transfer(61)).doctor_id,uuid(1));
    const result=await db.query('select public.sync_chart_finding_doctor($1,$2::uuid[]) count',[uuid(10),[uuid(61),uuid(62)]]);assert.equal(result.rows[0].count,2);
    assert.equal((await db.query('select count(*)::int count from private.hr_doctor_salary_payment_items')).rows[0].count,0);
    const permissions=await db.query("select has_function_privilege('authenticated','private.prepare_ortho_visit_invoice_item()','execute') exposed,has_function_privilege('anon','private.sync_ortho_visit_invoice_doctors()','execute') anonymous");
    assert.equal(permissions.rows[0].exposed,false);assert.equal(permissions.rows[0].anonymous,false);
  });
});
