const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');
const migration=fs.readFileSync('supabase/migrations/'+fs.readdirSync('supabase/migrations').find(name=>name.endsWith('_patient_consents.sql')),'utf8');
const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
test('consents enforce clinic permissions, preserve snapshots and finalized text, and reject stale edits',async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create schema auth; create schema private;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.user',true),'')::uuid$$;
    create function private.is_active_user() returns boolean language sql stable as $$select current_setting('test.active',true)='true'$$;
    create function private.is_admin() returns boolean language sql stable as $$select private.is_active_user() and current_setting('test.admin',true)='true'$$;
    create function private.has_page_permission(page text) returns boolean language sql stable as $$select private.is_active_user() and (private.is_admin() or page=any(string_to_array(current_setting('test.pages',true),',')))$$;
    create table public.patients(id uuid primary key,name text,patient_number bigint,birth_date date,phone text,address text,age integer,gender text);
    create table public.user_profiles(user_id uuid primary key,full_name text,active boolean,is_doctor boolean);
    insert into public.patients values('${id(1)}','Patient One',101,'1990-01-02','01000000000','Address',36,'female'),('${id(2)}','Patient Two',102,null,'',null,27,'male');
    insert into public.user_profiles values('${id(3)}','Doctor One',true,true),('${id(4)}','Reception',true,false),('${id(5)}','Inactive doctor',false,true);
    grant usage on schema public,private,auth to authenticated,anon;
    grant select on public.patients to authenticated;
    alter table public.patients enable row level security;
    create policy patient_read on public.patients for select to authenticated using(id<>'${id(2)}'::uuid);
    -- Deliberately hide other profiles to prove the narrow doctor lookup works.
    alter table public.user_profiles enable row level security;
    grant select on public.user_profiles to authenticated;
    create policy own_profile on public.user_profiles for select to authenticated using(user_id=auth.uid());
  `);
  await db.exec(migration);
  assert.equal((await db.query('select * from consent_templates')).rows.length,7);
  const template=(await db.query("select * from consent_templates where title_en='Dental implants'")).rows[0];
  await db.exec("set role anon");
  await assert.rejects(db.query('select * from consent_templates'),/permission denied/);
  await assert.rejects(db.query('select * from patient_consents'),/permission denied/);
  await assert.rejects(db.query('select * from list_consent_doctors()'),/permission denied/);
  await db.exec(`reset role; select set_config('test.user','${id(4)}',false); select set_config('test.active','true',false); select set_config('test.admin','false',false); select set_config('test.pages','patients',false); set role authenticated`);
  assert.equal((await db.query('select * from list_consent_doctors()')).rows[0].full_name,'Doctor One');
  assert.equal((await db.query('select * from user_profiles')).rows.length,1);
  assert.equal((await db.query("update consent_templates set body_en='unauthorized' returning id")).rows.length,0);
  const payload=[id(1),template.id,template.revision,'en','Custom implant consent','Specific patient wording',JSON.stringify({name:'Spoofed'}),id(3),'Doctor One'];
  const insert='insert into patient_consents(patient_id,template_id,template_revision,language,title,body,patient_data,doctor_id,doctor_name) values($1,$2,$3,$4,$5,$6,$7,$8,$9) returning *';
  const record=(await db.query(insert,payload)).rows[0];
  assert.equal(record.patient_data.name,'Patient One');
  assert.equal(record.patient_data.number,'101');
  assert.equal(record.created_by,id(4));
  assert.equal(record.status,'draft');
  assert.equal(record.finalized_at,null);
  await assert.rejects(db.query(insert,[id(2),...payload.slice(1)]),/no rows|row-level security/);
  await assert.rejects(db.query(insert,[...payload.slice(0,7),id(5),'Inactive doctor']),/active treating doctor/);
  const revised=(await db.query("update patient_consents set body='Individual change',doctor_id=null,doctor_name='Visiting specialist' where id=$1 and revision=1 returning *",[record.id])).rows[0];
  assert.equal(revised.revision,2);
  assert.equal((await db.query("update patient_consents set body='stale' where id=$1 and revision=1 returning *",[record.id])).rows.length,0);
  await assert.rejects(db.query('update patient_consents set patient_id=$1 where id=$2',[id(2),record.id]),/snapshot cannot change/);
  await assert.rejects(db.query("update patient_consents set patient_data='{}' where id=$1",[record.id]),/snapshot cannot change/);
  await db.exec("select set_config('test.admin','true',false)");
  await db.query("update consent_templates set body_en='Updated universal wording' where id=$1",[template.id]);
  assert.equal((await db.query('select revision from consent_templates where id=$1',[template.id])).rows[0].revision,2);
  assert.equal((await db.query('select body,template_revision from patient_consents where id=$1',[record.id])).rows[0].body,'Individual change');
  await assert.rejects(db.query(insert,payload),/Template changed/);
  await db.query("update patient_consents set status='finalized' where id=$1",[record.id]);
  const finalized=(await db.query('select * from patient_consents where id=$1',[record.id])).rows[0];
  assert.ok(finalized.finalized_at);
  await assert.rejects(db.query("update patient_consents set body='rewrite' where id=$1",[record.id]),/immutable/);
  await assert.rejects(db.query("update patient_consents set status='draft' where id=$1",[record.id]),/immutable/);
  await assert.rejects(db.query('delete from patient_consents where id=$1',[record.id]),/permission denied/);
  await db.query('update consent_templates set active=false where id=$1',[template.id]);
  assert.equal((await db.query('select body from patient_consents where id=$1',[record.id])).rows[0].body,'Individual change');
  await assert.rejects(db.query(insert,[payload[0],payload[1],3,...payload.slice(3)]),/active consent template/);
  await db.exec("select set_config('test.admin','false',false); select set_config('test.pages','appointments',false)");
  assert.equal((await db.query('select * from patient_consents')).rows.length,0);
  assert.equal((await db.query('select * from consent_templates')).rows.length,0);
  await assert.rejects(db.query('select * from list_consent_doctors()'),/Patient access required/);
  await db.exec("select set_config('test.pages','chart',false)");
  assert.equal((await db.query('select * from patient_consents')).rows.length,1);
  await db.exec("select set_config('test.active','false',false)");
  assert.equal((await db.query('select * from patient_consents')).rows.length,0);
});
